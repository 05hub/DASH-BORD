// 6. مثال على دورة حياة المهمة
// ============================================

/*
1. المالك ينشئ مهمة:
   "تحديث قاعدة البيانات"
   → تُحفظ على Firebase

2. عضو من جهاز آخر يرى المهمة:
   يفتح التطبيق → يسجل دخول → يرى المهمة

3. العضو يقبل المهمة:
   يضغط زر "استلام" → تُحدث على Firebase

4. المالك يرى أن المهمة تم استلامها:
   يفتح التطبيق → يرى "مستلم من: أحمد محمد"

5. العضو ينهي المهمة:
   يضغط "تمت المهمة" → تُحدث على Firebase
   → ظهور رسالة النهاية بالاسم والتاريخ

6. المالك يمسح رسالة النهاية (اختياري):
   يضغط "حذف رسالة الانتهاء" → تُحدث على Firebase
*/

