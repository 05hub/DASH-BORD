// 8. مفاهيم مهمة
// ============================================

/*
📌 Collections (المجموعات):
   - تشبه الجداول في قاعدة البيانات
   - المستخدمون في collection "users"
   - المهام في collection "tasks"

📌 Documents (الوثائق):
   - تشبه الصفوف في الجداول
   - كل مستخدم = وثيقة واحدة
   - كل مهمة = وثيقة واحدة

📌 Fields (الحقول):
   - البيانات داخل الوثيقة
   - username, password, label, role, etc.

📌 Async/Await:
   - تستخدم عندما تنتظر رد من الخادم
   - مثال: await db.collection('users').get()
   - الكود ينتظر حتى يأتي الرد
*/

